import AppKit
import Combine
import Observation
import SwiftData

@Observable
class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private let captureSubject = PassthroughSubject<Void, Never>()
    var captures: AnyPublisher<Void, Never> { captureSubject.eraseToAnyPublisher() }
    private var lastChangeCount: Int = 0
    private var timer: DispatchSourceTimer?
    private var modelContext: ModelContext?
    private var transformEngine: TransformEngine?
    private var hookEngine: HookEngine?

    // Lock to protect lastChangeCount from data races between background
    // timer queue and main queue writes (pattern adapted from exmen's
    // ScriptRunner NSLock guard).
    private let changeCountLock = NSLock()

    // In-memory tracking of last saved content for duplicate detection.
    // Using in-memory state instead of a SwiftData fetch because SwiftData's
    // fetchLimit+sortBy combination is unreliable on macOS 14 (known Apple bug).
    private var lastSavedContent: String?

    // Track whether the timer is currently suspended to avoid double-resume
    // crashes (matched from exmen's double-resume prevention pattern).
    private var isSuspended = false
    private let suspendLock = NSLock()

    var maxItems: Int {
        let stored = UserDefaults.standard.integer(forKey: "maxHistoryItems")
        return stored > 0 ? stored : 100  // Default 100 if not set or zero
    }

    // Cache for compiled regexes to avoid recompilation on every poll
    private var cachedPatternRegexes: [UUID: Regex<AnyRegexOutput>] = [:]

    private let ignoredTypes = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
        observeSleepWake()
    }

    // Get or compile regex for an IgnoredPattern
    private func getRegex(for pattern: IgnoredPattern) -> Regex<AnyRegexOutput>? {
        if let cached = cachedPatternRegexes[pattern.id] {
            return cached
        }
        guard let regex = try? Regex(pattern.pattern) else { return nil }
        cachedPatternRegexes[pattern.id] = regex
        return regex
    }

    // Invalidate cached regexes (call when patterns are modified)
    func invalidatePatternCache() {
        cachedPatternRegexes.removeAll()
    }

    func setModelContext(_ context: ModelContext) {
        self.modelContext = context

        // Seed lastSavedContent from the most recent history item so that
        // cross-session duplicates are prevented. Without this, lastSavedContent
        // starts as nil after every app launch, meaning any existing history item
        // copied by the user would bypass the in-memory guard and create a duplicate.
        var descriptor = FetchDescriptor<ClipboardItem>(
            sortBy: [SortDescriptor(\.timestamp, order: .reverse)]
        )
        descriptor.fetchLimit = 1
        if let recent = try? context.fetch(descriptor), let mostRecent = recent.first {
            lastSavedContent = mostRecent.content
        }
    }

    func setTransformEngine(_ engine: TransformEngine) {
        self.transformEngine = engine
    }

    func setHookEngine(_ engine: HookEngine) {
        self.hookEngine = engine
    }

    // MARK: - Sleep / Wake handling

    /// Subscribe to system sleep/wake notifications to safely pause and
    /// resume the polling timer. This prevents crashes caused by the timer
    /// firing into stale state immediately after wake.
    private func observeSleepWake() {
        let center = NSWorkspace.shared.notificationCenter

        center.addObserver(
            forName: NSWorkspace.willSleepNotification,
            object: nil, queue: .main
        ) { [weak self] _ in
            self?.handleSleep()
        }

        center.addObserver(
            forName: NSWorkspace.didWakeNotification,
            object: nil, queue: .main
        ) { [weak self] _ in
            self?.handleWake()
        }
    }

    private func handleSleep() {
        suspendLock.lock()
        defer { suspendLock.unlock() }

        guard !isSuspended, timer != nil else { return }
        timer?.suspend()
        isSuspended = true
    }

    private func handleWake() {
        // Refresh the change count so the first poll after wake doesn't
        // see a stale value and misfire.
        changeCountLock.lock()
        lastChangeCount = pasteboard.changeCount
        changeCountLock.unlock()

        suspendLock.lock()
        defer { suspendLock.unlock() }

        guard isSuspended, timer != nil else { return }
        timer?.resume()
        isSuspended = false
    }

    // MARK: - Timer lifecycle

    func start() {
        let queue = DispatchQueue(label: "com.clipass.monitor", qos: .utility)
        timer = DispatchSource.makeTimerSource(queue: queue)
        timer?.schedule(deadline: .now(), repeating: .milliseconds(500))
        timer?.setEventHandler { [weak self] in
            self?.poll()
        }
        timer?.resume()

        suspendLock.lock()
        isSuspended = false
        suspendLock.unlock()
    }

    func stop() {
        suspendLock.lock()
        // DispatchSource must be resumed before cancel if it is suspended,
        // otherwise it will crash.
        if isSuspended {
            timer?.resume()
            isSuspended = false
        }
        suspendLock.unlock()

        timer?.cancel()
        timer = nil
    }

    private func poll() {
        changeCountLock.lock()
        let currentChangeCount = lastChangeCount
        changeCountLock.unlock()

        let pasteboardCount = pasteboard.changeCount
        guard pasteboardCount != currentChangeCount else { return }

        changeCountLock.lock()
        lastChangeCount = pasteboardCount
        changeCountLock.unlock()

        // Check for ignored types (password managers, etc.)
        if let types = pasteboard.types {
            for type in types {
                if ignoredTypes.contains(type.rawValue) {
                    return // Skip secure content
                }
            }
        }

        // Image encoding happens here, on the timer queue, not on main.
        guard let captured = ClipboardCapture.read(from: pasteboard) else { return }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        DispatchQueue.main.async { [weak self] in
            guard let self = self, let context = self.modelContext else { return }
            switch captured {
            case .text(let content): self.recordText(content, sourceApp: sourceApp, context: context)
            case .image(let image): self.recordImage(image, sourceApp: sourceApp, context: context)
            }
        }
    }

    private func recordText(_ content: String, sourceApp: String?, context: ModelContext) {
        // Apply transforms if engine is available
        var transformedContent = content
        if let engine = transformEngine {
            transformedContent = engine.transform(content, sourceApp: sourceApp)
        }

        // Update clipboard if content was transformed
        if transformedContent != content {
            pasteboard.clearContents()
            pasteboard.setString(transformedContent, forType: .string)
            // Update lastChangeCount to avoid re-polling our own change
            changeCountLock.lock()
            lastChangeCount = pasteboard.changeCount
            changeCountLock.unlock()
        }

        if isIgnored(sourceApp, context: context) { return }

        // Check ignored patterns
        let patternDescriptor = FetchDescriptor<IgnoredPattern>()
        if let ignoredPatterns = try? context.fetch(patternDescriptor) {
            for ignoredPattern in ignoredPatterns where ignoredPattern.isEnabled {
                if let regex = getRegex(for: ignoredPattern),
                   transformedContent.contains(regex) {
                    return // Skip content matching ignore pattern
                }
            }
        }

        // Deduplicate: if this content already exists in history,
        // move it to the top by updating its timestamp instead of
        // inserting a new row. Image labels never match text.
        let searchContent = transformedContent
        var existingDescriptor = FetchDescriptor<ClipboardItem>(
            predicate: #Predicate { $0.content == searchContent && $0.imageHash == nil }
        )
        existingDescriptor.fetchLimit = 1
        if let existing = try? context.fetch(existingDescriptor).first {
            existing.timestamp = Date()
            existing.sourceApp = sourceApp
        } else {
            let item = ClipboardItem(
                content: transformedContent,
                sourceApp: sourceApp,
                timestamp: Date()
            )
            context.insert(item)
        }
        lastSavedContent = transformedContent

        // Prune old items if exceeding maxItems
        pruneOldItems(context: context)

        if (try? context.save()) != nil {
            captureSubject.send()
        }

        // Execute hooks after save
        hookEngine?.executeHooks(content: transformedContent, sourceApp: sourceApp)
    }

    // Transforms would rewrite the pasteboard as text, and patterns and hooks expect text, so images skip all three.
    private func recordImage(_ image: CapturedImage, sourceApp: String?, context: ModelContext) {
        if isIgnored(sourceApp, context: context) { return }

        let hash: String? = image.hash
        var existingDescriptor = FetchDescriptor<ClipboardItem>(predicate: #Predicate { $0.imageHash == hash })
        existingDescriptor.fetchLimit = 1
        if let existing = try? context.fetch(existingDescriptor).first {
            existing.timestamp = Date()
            existing.sourceApp = sourceApp
        } else {
            context.insert(ClipboardItem(content: image.label, sourceApp: sourceApp, timestamp: Date(),
                                         imageData: image.png, thumbnailData: image.thumbnail, imageHash: image.hash))
        }

        pruneOldItems(context: context)

        if (try? context.save()) != nil {
            captureSubject.send()
        }
    }

    private func isIgnored(_ sourceApp: String?, context: ModelContext) -> Bool {
        guard let sourceApp, let ignoredApps = try? context.fetch(FetchDescriptor<IgnoredApp>()) else { return false }
        return ignoredApps.contains { $0.isEnabled && (sourceApp == $0.bundleId || sourceApp.contains($0.bundleId)) }
    }

    private func pruneOldItems(context: ModelContext) {
        // Only prune unpinned items — pinned items are exempt from limits
        let descriptor = FetchDescriptor<ClipboardItem>(
            predicate: #Predicate { !$0.isPinned },
            sortBy: [SortDescriptor(\.timestamp, order: .reverse)]
        )

        guard let unpinnedItems = try? context.fetch(descriptor) else { return }

        if unpinnedItems.count > maxItems {
            let itemsToDelete = unpinnedItems.suffix(from: maxItems)
            for item in itemsToDelete {
                context.delete(item)
            }
        }
    }
}
